"""Table fragments for the v4 manuscript, from the experiment JSONs. Writes tex/tab_v4_*.tex."""
import os
import numpy as np
from common import load_json, HERE

T = os.path.join(HERE, 'tex')


def w(name, s):
    open(os.path.join(T, name), 'w').write('% Generated by paper_build/make_tables_v4.py. Do not edit by hand.\n' + s)


def pp(x):
    x = 0.0 if abs(x) < 0.005 else x
    return ('$-$' if x < 0 else '+' if x > 0 else '') + f'{abs(x):.2f}'


def neg(x, f='{:.1f}'):
    return ('$-$' if x < -1e-9 else '') + f.format(abs(x))


def sci(x):
    m, e = f'{x:.1e}'.split('e')
    return f'${m}\\times 10^{{{int(e)}}}$'


def yr(v):
    return 'none' if v is None else str(v)


# Experiment B: exact split of the change in the 2025 share
B = load_json('exp_b_physical_policy.json'); base = B['baseline']
rows = []
for key, lab, vals, fmt in (('ecs', 'ECS (\\textdegree C)', (2.0, 2.5, 3.5, 4.0, 5.0), '{:.1f}'), ('psi2', '$\\psi_2$ ($\\times 10^{-3}$)', (0.0017, 0.0026, 0.0052, 0.0069), None)):
    first = True
    for r in B['rows']:
        if r['param'] != key or not any(abs(r['value'] - v) < 1e-9 for v in vals):
            continue
        sp = r['split']; v = fmt.format(r['value']) if fmt else f"{1e3 * r['value']:.1f}"
        rows.append(f"{lab if first else ''} & {v} & {100 * r['fixed']['share_2025']:.1f} & {100 * r['reopt']['share_2025']:.1f} & {r['fixed']['feedback_2025']:.2f} & {r['reopt']['feedback_2025']:.2f} & "
                    f"{pp(100 * sp['physical'])} & {pp(100 * sp['abatement'])} & {pp(100 * sp['savings'])} & {pp(100 * sp['total'])} & "
                    f"{r['reopt']['cumE_2100']:,.0f} \\\\")
        first = False
    rows.append('\\midrule')
rows = rows[:-1]
w('tab_v4_policy.tex', '\\begin{tabular}{lrrrrrrrrrr}\n\\toprule\n & & \\multicolumn{2}{c}{Share (\\%)} & \\multicolumn{2}{c}{Feedback (\\$/tCO$_2$)} & \\multicolumn{4}{c}{Change in share (percentage points)} & \\\\\n'
  '\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-10}\nParameter & Value & Fixed & Re-opt. & Fixed & Re-opt. & Physical & Abatement & Savings & Total & Emissions 2020--2100 \\\\\n\\midrule\n'
  + '\n'.join(rows) + f"\n\\midrule\nDICE-2023 & & \\multicolumn{{2}}{{c}}{{{100 * base['share_2025']:.1f}}} & \\multicolumn{{2}}{{c}}{{{base['feedback_2025']:.2f}}} & & & & & {base['cumE_2100']:,.0f} \\\\\n\\bottomrule\n\\end{{tabular}}\n")

