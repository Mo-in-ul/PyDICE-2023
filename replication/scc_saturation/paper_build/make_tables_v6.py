def w(name, s):
    open(os.path.join(T, name), 'w').write('% Generated by paper_build/make_tables_v6.py. Do not edit by hand.\n' + s)


def sg(x, f='{:.2f}'):
    t = f.format(abs(x))
    z = float(t) == 0.0
    return ('' if z else '$-$' if x < 0 else '+') + t


def neg(x, f='{:.2f}'):
    t = f.format(abs(x))
    return ('$-$' if x < 0 and float(t) != 0 else '') + t


def small(x):
    return '$<$0.0001' if abs(x) < 5e-5 else f'{abs(x):.4f}'


def pp(x):
    x = 0.0 if abs(x) < 0.005 else x
    return ('$-$' if x < 0 else '+' if x > 0 else '') + f'{abs(x):.2f}'


