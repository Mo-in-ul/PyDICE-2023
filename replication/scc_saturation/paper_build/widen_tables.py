"""Write full-width copies of tables for the journal layout: tex/tab_X.tex -> tex/wide_tab_X.tex.

Each copy turns tabular into tabular* at \\textwidth with \\extracolsep{\\fill}; the content is unchanged.
Run after the make_tables scripts.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
TEX = os.path.join(HERE, 'tex')
NAMES = ['1p5c_cap', 'envelope', 'mc_bound', 'pulse_sweep', 'sub_sobol', 'tlo_effect', 'v4_scc2025', 'v6_ccsweep', 'v6_omit']

for name in NAMES:
    src = f'tab_{name}.tex'
    s = open(os.path.join(TEX, src)).read()
    s, n = re.subn(r'\\begin\{tabular\}\{', r'\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}', s, count=1)
    assert n == 1, src
    s, n = re.subn(r'\\end\{tabular\}', r'\\end{tabular*}', s, count=1)
    assert n == 1, src
    head = f'% Generated by paper_build/widen_tables.py from {src}. Do not edit by hand.\n'
    open(os.path.join(TEX, f'wide_tab_{name}.tex'), 'w').write(head + s)
print('wide tables written:', len(NAMES))
