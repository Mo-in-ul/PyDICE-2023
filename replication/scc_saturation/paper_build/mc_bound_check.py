"""Robustness of the Monte Carlo to the lower temperature bound, descriptive statistics only.

Three samples of the converged draws:
  all          every draw (the primary results),
  no_bound     draws whose optimal path never reaches the 0.01 C lower bound on T_AT (min T > 0.01 + 1e-5),
  restricted   draws whose optimal path never falls below 0.5 C, the stability bound of the GAMS program.
The third is a restricted-sample sensitivity analysis: it drops parameter combinations that lead to very
low-temperature paths, which is not the same as re-optimizing every draw with a 0.5 C bound imposed.
For each sample: median, 5th and 95th percentile of the 2025 and 2100 feedback share, fraction negative, and
standardized regression coefficients of the 2025 share (standardized with the full-sample moments so the
columns are comparable). Sobol indices are not computed for the subsets: selecting draws on their outcome makes
the inputs dependent, and the variance decomposition of sobol.py on the full sample remains the reference.
Writes results/mc_bound_check.json and tex/tab_mc_bound.tex."""
import os
import numpy as np
from common import HERE, save_json
import mc_v2 as V
from fig_mc2 import load

LAB = {'rho': '$\\rho$', 'elasmu': '$\\varphi$', 'ecs': 'ECS', 'psi2': '$\\psi_2$', 'a3': 'Damage exponent',
       'irC': '$\\sigma_C$', 'irT': '$\\sigma_T$', 'eland0': '$E_{\\mathrm{land}}(0)$'}


def min_T(o):
    return o.get('min_T', 1.0)        # the seven SLSQP fallback draws carry no min_T; none of them is a deep-removal path


def summarize(P, y25, y100, mu, sd):
    out = {'n': int(len(y25))}
    for name, y in (('share_2025', y25), ('share_2100', y100)):
        out[name] = {'p5': float(np.percentile(y, 5)), 'p50': float(np.median(y)), 'p95': float(np.percentile(y, 95)),
                     'neg': float(np.mean(y < 0))}
    Z = (P - mu) / sd
    X = np.column_stack([np.ones(len(Z)), Z]); beta = np.linalg.lstsq(X, y25, rcond=None)[0]
    out['coef_pp_per_sd'] = dict(zip(V.KEYS, beta[1:].tolist()))
    out['R2'] = float(1 - np.var(y25 - X @ beta) / np.var(y25))
    return out


if __name__ == '__main__':
    rec = {o['draw']: o for o in load()}
    idx = np.array(sorted(rec))
    P = np.array([[rec[k]['params'][kk] for kk in V.KEYS] for k in idx])
    y25 = np.array([100 * rec[k]['share_2025'] for k in idx]); y100 = np.array([100 * rec[k]['share_2100'] for k in idx])
    mT = np.array([min_T(rec[k]) for k in idx])
    hit = mT <= 0.01 + 1e-5; low = mT < 0.5
    mu, sd = P.mean(0), P.std(0)
    res = {'n_bound_reached': int(hit.sum()), 'n_below_half': int(low.sum()),
           'bound_draws_mean_z': dict(zip(V.KEYS, ((P[hit] - mu) / sd).mean(0).tolist())),
           'below_half_mean_z': dict(zip(V.KEYS, ((P[low] - mu) / sd).mean(0).tolist())),
           'all': summarize(P, y25, y100, mu, sd),
           'no_bound': summarize(P[~hit], y25[~hit], y100[~hit], mu, sd),
           'restricted': summarize(P[~low], y25[~low], y100[~low], mu, sd)}
    save_json(res, 'mc_bound_check.json')
    C = ('all', 'no_bound', 'restricted')
    for kk in C:
        r = res[kk]
        print(kk, r['n'], {n: {q: round(v, 2) for q, v in r[n].items()} for n in ('share_2025', 'share_2100')}, 'R2', round(r['R2'], 3))
        print('  coef', {k: round(v, 2) for k, v in r['coef_pp_per_sd'].items()})
    print('bound draws mean z', {k: round(v, 2) for k, v in res['bound_draws_mean_z'].items()})
    print('below-half draws mean z', {k: round(v, 2) for k, v in res['below_half_mean_z'].items()})

    def sg(x):
        return ('$-$' if x < -0.005 else '+' if x > 0.005 else '') + f'{abs(x):.2f}'
    L = [f"{LAB[k]} & " + ' & '.join(sg(res[c]['coef_pp_per_sd'][k]) for c in C) + ' \\\\' for k in V.KEYS]
    L.append(f"$R^2$ (linear) & " + ' & '.join(f"{res[c]['R2']:.2f}" for c in C) + ' \\\\')
    L.append('\\midrule')
    L.append('Draws & ' + ' & '.join(str(res[c]['n']) for c in C) + ' \\\\')
    L.append('Median share 2025 (\\%) & ' + ' & '.join(f"{res[c]['share_2025']['p50']:.1f}" for c in C) + ' \\\\')
    L.append('5th--95th pct.\\ 2025 (\\%) & ' + ' & '.join(f"{res[c]['share_2025']['p5']:.1f}--{res[c]['share_2025']['p95']:.1f}" for c in C) + ' \\\\')
    L.append('Median share 2100 (\\%) & ' + ' & '.join(f"{res[c]['share_2100']['p50']:.1f}" for c in C) + ' \\\\')
    L.append('Negative in 2100 (\\%) & ' + ' & '.join(f"{100 * res[c]['share_2100']['neg']:.0f}" for c in C) + ' \\\\')
    s = ("\\begin{tabular}{lrrr}\n\\toprule\n & All draws & Never at 0.01\\,\\textdegree C & Never below 0.5\\,\\textdegree C \\\\\n\\midrule\n"
         "\\multicolumn{4}{l}{\\textit{Regression of the 2025 share (pp per s.d.)}} \\\\\n" + '\n'.join(L) + "\n\\bottomrule\n\\end{tabular}\n")
    open(os.path.join(HERE, 'tex', 'tab_mc_bound.tex'), 'w').write('% Generated by paper_build/mc_bound_check.py. Do not edit by hand.\n' + s)
