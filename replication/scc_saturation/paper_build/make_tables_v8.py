def w(name, s):
    open(os.path.join(T, name), 'w').write('% Generated by paper_build/make_tables_v8.py. Do not edit by hand.\n' + s)


def sg(x, f='{:.2f}'):
    t = f.format(abs(x))
    return ('' if float(t) == 0.0 else '$-$' if x < 0 else '+') + t


def neg(x, f='{:.2f}'):
    t = f.format(abs(x))
    return ('$-$' if x < 0 and float(t) != 0 else '') + t


def pp(x):
    x = 0.0 if abs(x) < 0.005 else x
    return ('$-$' if x < 0 else '+' if x > 0 else '') + f'{abs(x):.2f}'


